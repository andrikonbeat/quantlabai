#!/usr/bin/env python3
"""Deterministic, idempotent sync of QuantLab skills from repo to live.

REQ-822/901: the repo directory ``ai/opencode/skills/`` is the single source
of truth for QuantLab-owned skills. The live copies under
``~/.config/opencode/skills/`` are generated from it by this script; hand-
editing live skills is not permitted.

Managed allowlist (sorted, deterministic): all ``quantlab-*`` skills present
in the repo. Live skill directories outside the allowlist are never touched.
Sync uses the same ``SyncDriver`` discipline as prompt sync: deterministic
byte-equality, idempotent, supports ``--dry-run`` and ``--check``, and
refreshes the skill registry after sync.

Usage::

    python3 ai/opencode/sync_skills.py                # copy repo -> live
    python3 ai/opencode/sync_skills.py --dry-run      # report, write nothing
    python3 ai/opencode/sync_skills.py --check        # exit 1 on any drift

Idempotent: identical bytes are never rewritten; a second run is a no-op.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

# Ensure sync_common.py is importable when this module is loaded dynamically
# (e.g. via importlib in tests).
sys.path.insert(0, str(Path(__file__).resolve().parent))
from sync_common import SyncDriver

REPO_DIR = Path(__file__).resolve().parent / "skills"
LIVE_DIR = Path.home() / ".config" / "opencode" / "skills"


def managed_skill_names(repo_dir: Path = REPO_DIR) -> list[str]:
    """Sorted allowlist of QuantLab-owned skill directory names present in the repo.

    Includes every top-level directory under ``repo_dir`` whose name starts
    with ``quantlab-``. Names without a repo copy are omitted so the allowlist
    never names a skill the repo does not hold. Sorted for determinism
    regardless of filesystem order.
    """
    names = sorted(
        p.name
        for p in repo_dir.iterdir()
        if p.is_dir() and p.name.startswith("quantlab-")
    )
    return names


def _skill_dirs_changed(repo_dir: Path, live_dir: Path, names: list[str]) -> list[str]:
    """Return skill names whose live tree differs from the repo tree."""
    changed: list[str] = []
    for name in names:
        repo_skill = repo_dir / name
        live_skill = live_dir / name
        if not repo_skill.is_dir():
            continue
        if not live_skill.is_dir():
            changed.append(name)
            continue
        repo_files = sorted(p.relative_to(repo_skill) for p in repo_skill.rglob("*") if p.is_file())
        live_files = sorted(p.relative_to(live_skill) for p in live_skill.rglob("*") if p.is_file())
        if repo_files != live_files:
            changed.append(name)
            continue
        for rel in repo_files:
            if (repo_skill / rel).read_bytes() != (live_skill / rel).read_bytes():
                changed.append(name)
                break
    return sorted(changed)


def sync(repo_dir: Path = REPO_DIR, live_dir: Path = LIVE_DIR, *, dry_run: bool = False) -> list[str]:
    """Copy managed skills from repo to live, tree-for-tree.

    Returns the sorted list of skill names that were (or, with
    ``dry_run=True``, would be) written. Idempotent: a skill whose live tree
    already equals the repo tree is skipped and not listed.
    """
    live_dir.mkdir(parents=True, exist_ok=True)
    names = managed_skill_names(repo_dir)
    changed = _skill_dirs_changed(repo_dir, live_dir, names)
    for name in changed:
        repo_skill = repo_dir / name
        live_skill = live_dir / name
        if not dry_run:
            if live_skill.exists():
                shutil.rmtree(live_skill)
            shutil.copytree(repo_skill, live_skill)
    if changed and not dry_run:
        _refresh_registry(live_dir)
    return changed


def check(repo_dir: Path = REPO_DIR, live_dir: Path = LIVE_DIR) -> list[str]:
    """Return sorted managed skill names whose live tree differs from the repo.

    Empty list means parity holds tree-for-tree.
    """
    names = managed_skill_names(repo_dir)
    return _skill_dirs_changed(repo_dir, live_dir, names)


def _refresh_registry(live_dir: Path) -> None:
    """Refresh the OpenCode skill registry after a live sync.

    Writes a minimal ``skill-registry.md`` index under ``~/.config/opencode/``
    listing every synced skill name and its path. This is a best-effort
    side-effect; failures are logged but do not stop the sync.
    """
    registry_path = live_dir.parent / "skill-registry.md"
    try:
        skills = sorted(
            p.name for p in live_dir.iterdir() if p.is_dir() and p.name.startswith("quantlab-")
        )
        lines = [
            "# OpenCode Skill Registry",
            "",
            "Auto-generated by `sync_skills.py`. Do not hand-edit.",
            "",
            "| Skill | Path |",
            "|-------|------|",
        ]
        for name in skills:
            lines.append(f"| `{name}` | `{live_dir / name}` |")
        lines.append("")
        registry_path.write_text("\n".join(lines), encoding="utf-8")
    except Exception as exc:  # pragma: no cover — best-effort side-effect
        print(f"WARNING: registry refresh failed: {exc}", file=sys.stderr)


def _main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="sync_skills",
        description=__doc__.split("Usage::", 1)[0],
    )
    parser.add_argument(
        "--repo", type=Path, default=REPO_DIR, help="repo skills dir (default: %(default)s)"
    )
    parser.add_argument(
        "--live", type=Path, default=LIVE_DIR, help="live skills dir (default: %(default)s)"
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="report what would change, write nothing")
    mode.add_argument("--check", action="store_true", help="exit 1 if any managed file drifted")
    args = parser.parse_args(argv)

    if args.check:
        drifted = check(args.repo, args.live)
        if drifted:
            print(f"DRIFT ({len(drifted)}): " + ", ".join(drifted))
            return 1
        print("parity ok")
        return 0

    changed = sync(args.repo, args.live, dry_run=args.dry_run)
    if changed:
        verb = "would update" if args.dry_run else "updated"
        print(f"{verb} ({len(changed)}): " + ", ".join(changed))
    else:
        print("already in sync")
    return 0


if __name__ == "__main__":
    sys.exit(_main())
