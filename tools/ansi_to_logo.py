#!/usr/bin/env python3
"""
Convert ANSI escape code logo to Go logo format for QuantLab TUI.
Supports half-block (▀/▄) mode with truecolor ANSI.
"""

import re
import sys
from pathlib import Path

def parse_ansi_file(ansi_path: str):
    """Parse ANSI file and extract pixel grid."""
    content = Path(ansi_path).read_text()
    
    # Regex for ANSI truecolor: \033[38;2;R;G;B;48;2;R;G;Bm▀
    ansi_pattern = re.compile(r'\x1b\[38;2;(\d+);(\d+);(\d+)(?:;48;2;\d+;\d+;\d+)?m(▀|▄|█| )')
    
    matches = ansi_pattern.findall(content)
    
    if not matches:
        # Try simpler pattern
        ansi_pattern = re.compile(r'\x1b\[[0-9;]*m(▀|▄|█| )')
        matches = [(0,0,0, m) for m in ansi_pattern.findall(content)]
    
    print(f"Found {len(matches)} colored characters")
    
    # Determine grid dimensions from newlines in original
    lines = content.split('\n')
    rows = len([l for l in lines if l.strip()])
    
    # Estimate cols from first line
    first_line_chars = ansi_pattern.findall(lines[0]) if lines else []
    cols = len(first_line_chars)
    
    print(f"Estimated grid: {rows} rows x {cols} cols")
    
    # Build grid
    grid = []
    colors = []
    row = []
    row_colors = []
    
    for r, g, b, char in matches:
        row.append(1 if char in '▀▄█' else 0)
        row_colors.append((r, g, b))
        if len(row) == cols:
            grid.append(row)
            colors.append(row_colors)
            row = []
            row_colors = []
    
    return grid, colors

def generate_go_code(grid, colors, logo_name="custom"):
    """Generate Go code for the logo."""
    # Convert grid to strings
    lines = []
    for row in grid:
        line = '"' + "".join("█" if c else " " for c in row) + '",'
        lines.append("        " + line)
    
    # Extract unique colors from palette (top-to-bottom gradient)
    palette = []
    for row_colors in colors:
        if row_colors:
            r = sum(int(c[0]) for c in row_colors) // len(row_colors)
            g = sum(int(c[1]) for c in row_colors) // len(row_colors)
            b = sum(int(c[2]) for c in row_colors) // len(row_colors)
            palette.append((r, g, b))
    
    # Deduplicate similar colors
    unique_palette = []
    for c in palette:
        is_unique = True
        for uc in unique_palette:
            if all(abs(c[i] - uc[i]) <= 10 for i in range(3)):
                is_unique = False
                break
        if is_unique:
            unique_palette.append(c)
    
    # Limit to 6 colors for gradient
    if len(unique_palette) > 6:
        step = len(unique_palette) / 6
        unique_palette = [unique_palette[int(i * step)] for i in range(6)]
    
    palette_lines = []
    for r, g, b in unique_palette:
        palette_lines.append(f'        lipgloss.Color("#{r:02x}{g:02x}{b:02x}"),')
    
    go_code = f'''// Code generated by ansi_to_logo.py - DO NOT EDIT
package theme

import (
	"strings"

	"github.com/charmbracelet/lipgloss"
)

var {logo_name}LogoLines = []string{{
{chr(10).join(lines)}
}}

var {logo_name}GradientColors = []lipgloss.Color{{{chr(10).join(palette_lines)}
}}

func Render{logo_name.title()}Logo() string {{
	total := len({logo_name}LogoLines)
	if total == 0 {{
		return ""
	}}

	bands := len({logo_name}GradientColors)
	var b strings.Builder

	for i, line := range {logo_name}LogoLines {{
		bandIdx := (i * bands) / total
		if bandIdx >= bands {{
			bandIdx = bands - 1
		}}
		style := lipgloss.NewStyle().Foreground({logo_name}GradientColors[bandIdx])
		b.WriteString(style.Render(line))
		if i < total-1 {{
			b.WriteByte('\\n')
		}}
	}}

	return b.String()
}}
'''
    return go_code

def main():
    if len(sys.argv) < 2:
        print("Usage: python3 ansi_to_logo.py <ansi_file> [logo_name]")
        sys.exit(1)
    
    ansi_file = sys.argv[1]
    logo_name = sys.argv[2] if len(sys.argv) > 2 else "custom"
    
    grid, colors = parse_ansi_file(ansi_file)
    
    if not grid:
        print("No grid extracted!")
        sys.exit(1)
    
    go_code = generate_go_code(grid, colors, logo_name)
    print(go_code)

if __name__ == "__main__":
    main()
