#!/usr/bin/env python3
"""
Clean futuristic banner logo for QuantLab - uses gradient blocks with text.
"""

def create_clean_banner(width=70, height=12):
    """Create a clean gradient banner with QuantLab text."""
    
    # QuantLab brand gradient (from the ANSI: dark → teal → green → gold → purple)
    gradient = [
        (0x0d, 0x1b, 0x2a),  # 0: dark navy
        (0x14, 0x33, 0x45),  # 1: dark blue
        (0x1f, 0x4d, 0x5e),  # 2: blue
        (0x2d, 0x6a, 0x7a),  # 3: teal-blue
        (0x3a, 0x8f, 0x9a),  # 4: teal
        (0x4e, 0xb8, 0x9f),  # 5: mint-teal
        (0x6f, 0xd9, 0x9f),  # 6: mint
        (0x95, 0xe8, 0xad),  # 7: light green
        (0xb8, 0xf5, 0xc8),  # 8: pale green
        (0xd4, 0xeb, 0x8a),  # 9: yellow-green
        (0xeb, 0xd8, 0x6a),  # 10: gold
        (0xf1, 0xca, 0x93),  # 11: peach
        (0xeb, 0xbc, 0xba),  # 12: mauve
        (0xc4, 0xa7, 0xe7),  # 13: lavender
    ]
    
    # "QUANTLAB" in block letters (7x5)
    font = {
        'Q': ["████", "█  █", "█  █", "█ ██", "████"],
        'U': ["█  █", "█  █", "█  █", "█  █", "████"],
        'A': ["████", "█  █", "████", "█  █", "█  █"],
        'N': ["█  █", "██ █", "█ ██", "█  █", "█  █"],
        'T': ["█████", "  █  ", "  █  ", "  █  ", "  █  "],
        'L': ["█    ", "█    ", "█    ", "█    ", "████"],
        'A': ["████", "█  █", "████", "█  █", "█  █"],
        'B': ["████", "█  █", "████", "█  █", "████"],
    }
    
    text = "QUANTLAB"
    char_w = 5  # 4 + 1 space
    text_width = len(text) * char_w - 1
    start_x = (width - text_width) // 2
    start_y = (height - 5) // 2
    
    lines = []
    for row in range(height):
        # Background gradient color for this row
        color_idx = min(row * len(gradient) // height, len(gradient) - 1)
        
        line = []
        for col in range(width):
            # Check if we're in text area
            tx = col - start_x
            ty = row - start_y
            
            in_text = False
            if 0 <= ty < 5 and 0 <= tx < text_width:
                char_idx = tx // char_w
                px = tx % char_w
                if char_idx < len(text) and px < 4:
                    ch = text[char_idx]
                    if font[ch][ty][px] == '█':
                        in_text = True
            
            if in_text:
                # Text uses inverse: bright on dark
                line.append("█")
            else:
                # Background pattern: subtle scanlines
                if (col + row) % 4 == 0:
                    line.append("▀")
                elif col % 10 == 0:
                    line.append("▄")
                else:
                    line.append(" ")
        
        lines.append("".join(line))
    
    # Use 6 colors for gradient
    palette = [gradient[i * len(gradient) // 6] for i in range(6)]
    
    return lines, palette

def generate_go_code(lines, palette, logo_name="futuristic"):
    palette_lines = []
    for r, g, b in palette:
        palette_lines.append(f'        lipgloss.Color("#{r:02x}{g:02x}{b:02x}"),')
    
    line_strs = [f'        "{line}",' for line in lines]
    
    return f'''// Code generated by clean_futuristic.py - DO NOT EDIT
package theme

import (
	"strings"

	"github.com/charmbracelet/lipgloss"
)

var {logo_name}LogoLines = []string{{
{chr(10).join(line_strs)}
}}

var {logo_name}GradientColors = []lipgloss.Color{{{chr(10).join(palette_lines)}
}}

func Render{logo_name.title()}Logo() string {{
	total := len({logo_name}LogoLines)
	if total == 0 {{
		return ""
	}}

	bands := len({logo_name}GradientColors)
	var b strings.Builder

	for i, line := range {logo_name}LogoLines {{
		bandIdx := (i * bands) / total
		if bandIdx >= bands {{
			bandIdx = bands - 1
		}}
		style := lipgloss.NewStyle().Foreground({logo_name}GradientColors[bandIdx])
		b.WriteString(style.Render(line))
		if i < total-1 {{
			b.WriteByte('\\n')
		}}
	}}

	return b.String()
}}
'''

if __name__ == "__main__":
    lines, palette = create_clean_banner(70, 12)
    code = generate_go_code(lines, palette, "futuristic")
    print(code)
