#!/usr/bin/env python3
"""
Simple clean futuristic banner - solid gradient with centered text.
"""

def create_simple_banner(width=64, height=10):
    """Create a clean gradient banner."""
    
    # Gradient from the ANSI: dark navy → blue → teal → mint → green → gold → purple
    gradient = [
        (0x0d, 0x1b, 0x2a),  # dark navy
        (0x14, 0x33, 0x45),  # dark blue
        (0x1f, 0x4d, 0x5e),  # blue
        (0x2d, 0x6a, 0x7a),  # teal-blue
        (0x3a, 0x8f, 0x9a),  # teal
        (0x4e, 0xb8, 0x9f),  # mint-teal
        (0x6f, 0xd9, 0x9f),  # mint
        (0x95, 0xe8, 0xad),  # light green
        (0xb8, 0xf5, 0xc8),  # pale green
        (0xd4, 0xeb, 0x8a),  # yellow-green
        (0xeb, 0xd8, 0x6a),  # gold
        (0xf1, 0xca, 0x93),  # peach
        (0xeb, 0xbc, 0xba),  # mauve
        (0xc4, 0xa7, 0xe7),  # lavender
    ]
    
    lines = []
    for row in range(height):
        color_idx = min(row * len(gradient) // height, len(gradient) - 1)
        
        # Create line with subtle texture
        line = []
        for col in range(width):
            # Subtle pattern: every few chars
            if col % 8 == 0:
                line.append("▀")
            elif col % 8 == 4:
                line.append("▄")
            else:
                line.append("█")
        lines.append("".join(line))
    
    # Use 6 colors for gradient
    palette = [gradient[i * len(gradient) // 6] for i in range(6)]
    
    return lines, palette

def create_text_banner(width=64, height=12):
    """Create banner with QUANTLAB text."""
    
    gradient = [
        (0x0d, 0x1b, 0x2a), (0x14, 0x33, 0x45), (0x1f, 0x4d, 0x5e),
        (0x2d, 0x6a, 0x7a), (0x3a, 0x8f, 0x9a), (0x4e, 0xb8, 0x9f),
        (0x6f, 0xd9, 0x9f), (0x95, 0xe8, 0xad), (0xb8, 0xf5, 0xc8),
        (0xd4, 0xeb, 0x8a), (0xeb, 0xd8, 0x6a), (0xf1, 0xca, 0x93),
        (0xeb, 0xbc, 0xba), (0xc4, 0xa7, 0xe7),
    ]
    
    # Simple 5x5 font for QUANTLAB
    font = {
        'Q': ["████", "█  █", "█ ██", "█  █", "████"],
        'U': ["█  █", "█  █", "█  █", "█  █", "████"],
        'A': ["████", "█  █", "████", "█  █", "█  █"],
        'N': ["██ █", "█ ██", "█  █", "█  █", "█  █"],
        'T': ["█████", "  █  ", "  █  ", "  █  ", "  █  "],
        'L': ["█    ", "█    ", "█    ", "█    ", "████"],
        'B': ["████", "█  █", "████", "█  █", "████"],
    }
    
    text = "QUANTLAB"
    char_width = 5  # 4px + 1 space
    text_width = len(text) * char_width - 1
    
    lines = []
    for row in range(height):
        color_idx = min(row * len(gradient) // height, len(gradient) - 1)
        
        line = []
        # Left padding
        left_pad = (width - text_width) // 2
        line.extend([" " if (c + row) % 4 else "▀" for c in range(left_pad)])
        
        # Text rendering
        for char_idx, ch in enumerate(text):
            if 0 <= row < 5:
                char_pattern = font.get(ch, ["█" * 4] * 5)[row]
                for px, c in enumerate(char_pattern):
                    if c == '█':
                        line.append("█")
                    else:
                        line.append(" ")
            if char_idx < len(text) - 1:
                line.append(" ")  # space between chars
        
        # Right padding
        right_pad = width - len(line)
        line.extend([" " if (c + row) % 4 else "▄" for c in range(right_pad)])
        
        lines.append("".join(line))
    
    palette = [gradient[i * len(gradient) // 6] for i in range(6)]
    return lines, palette

def generate_go_code(lines, palette, logo_name="futuristic"):
    palette_lines = [f'        lipgloss.Color("#{r:02x}{g:02x}{b:02x}"),' for r,g,b in palette]
    line_strs = [f'        "{line}",' for line in lines]
    
    return f'''// Code generated by simple_futuristic.py - DO NOT EDIT
package theme

import (
	"strings"

	"github.com/charmbracelet/lipgloss"
)

var {logo_name}LogoLines = []string{{
{chr(10).join(line_strs)}
}}

var {logo_name}GradientColors = []lipgloss.Color{{{chr(10).join(palette_lines)}
}}

func Render{logo_name.title()}Logo() string {{
	total := len({logo_name}LogoLines)
	if total == 0 {{ return "" }}
	bands := len({logo_name}GradientColors)
	var b strings.Builder
	for i, line := range {logo_name}LogoLines {{
		bandIdx := (i * bands) / total
		if bandIdx >= bands {{ bandIdx = bands - 1 }}
		style := lipgloss.NewStyle().Foreground({logo_name}GradientColors[bandIdx])
		b.WriteString(style.Render(line))
		if i < total-1 {{ b.WriteByte('\\n') }}
	}}
	return b.String()
}}
'''

if __name__ == "__main__":
    # Generate both versions
    lines1, pal1 = create_simple_banner(64, 10)
    code1 = generate_go_code(lines1, pal1, "futuristic")
    print("=== SIMPLE BANNER ===")
    print(code1)
    
    lines2, pal2 = create_text_banner(64, 12)
    code2 = generate_go_code(lines2, pal2, "futuristicText")
    print("\n=== TEXT BANNER ===")
