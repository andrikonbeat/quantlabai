def hex_to_rgb(hex_color: str) -> tuple:
    hex_color = hex_color.lstrip('#')
    return tuple(int(hex_color[i:i+2], 16) for i in (0, 2, 4))

def render_logo(grid: list, palette: list, use_braille: bool = True) -> str:
    rows = len(grid)
    cols = len(grid[0]) if rows > 0 else 0
    
    if use_braille:
        braille_rows = (rows + 3) // 4
        braille_cols = (cols + 1) // 2
        output_lines = []
        
        for br in range(braille_rows):
            line_parts = []
            for bc in range(braille_cols):
                dots = 0
                for dr in range(4):
                    for dc in range(2):
                        r = br * 4 + dr
                        c = bc * 2 + dc
                        if r < rows and c < cols and grid[r][c]:
                            dot_map = {0: 1, 1: 2, 2: 3, 3: 7, 4: 4, 5: 5, 6: 6, 7: 8}
                            idx = dr * 2 + dc
                            if idx in dot_map:
                                dots |= BRAILLE_DOTS[dot_map[idx]]
                char = chr(0x2800 + dots) if dots else " "
                color_idx = min(br * len(palette) // max(1, braille_rows), len(palette) - 1)
                r, g, b = palette[color_idx]
                line_parts.append("\033[38;2;{};{};{}m{}\033[0m".format(r, g, b, char))
            output_lines.append("".join(line_parts))
        return "\n".join(output_lines)
    else:
        output_lines = []
        for r, row in enumerate(grid):
            color_idx = min(r * len(palette) // max(1, rows), len(palette) - 1)
            r_, g_, b_ = palette[color_idx]
            line = ""
            for c, cell in enumerate(row):
                if cell:
                    line += "\033[38;2;{};{};{}m{}\033[0m".format(r_, g_, b_, BLOCK_FULL)
                else:
                    line += " "
            output_lines.append(line)
        return "\n".join(output_lines)

