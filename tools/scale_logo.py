#!/usr/bin/env python3
"""
Scale down the futuristic logo to a reasonable TUI width (80 cols).
"""

# Original extracted grid (simplified - all solid)
# The ANSI is essentially a gradient banner. Let's create a scaled version.

def create_scaled_logo(width=80, height=16):
    """Create a scaled-down version of the futuristic gradient banner."""
    lines = []
    
    # QuantLab brand gradient: dark blue -> teal -> green -> gold -> purple
    gradient = [
        (0x0d, 0x1b, 0x2a),  # dark navy
        (0x1a, 0x3a, 0x4a),  # dark blue
        (0x2d, 0x6a, 0x7a),  # blue
        (0x3a, 0x9b, 0xa7),  # cyan
        (0x4e, 0xc9, 0xb8),  # teal
        (0x6f, 0xe6, 0xa8),  # mint
        (0x8f, 0xf0, 0xb2),  # light green
        (0xb8, 0xf5, 0xc8),  # pale green
    ]
    
    # Create gradient banner with subtle pattern
    for row in range(height):
        # Pick color based on row
        color_idx = min(row * len(gradient) // height, len(gradient) - 1)
        r, g, b = gradient[color_idx]
        
        # Add subtle variation: not all solid, some "scanline" effect
        line_chars = []
        for col in range(width):
            # Every 4th column slightly different (scanline effect)
            if (col + row) % 8 == 0:
                line_chars.append("▀")
            elif col % 20 == 0:
                line_chars.append("▄")
            else:
                line_chars.append("█")
        lines.append("".join(line_chars))
    
    return lines, gradient[:6]  # Return 6 colors for Go gradient

def generate_go_code(lines, palette, logo_name="futuristic"):
    palette_lines = []
    for r, g, b in palette:
        palette_lines.append(f'        lipgloss.Color("#{r:02x}{g:02x}{b:02x}"),')
    
    line_strs = []
    for line in lines:
        line_strs.append(f'        "{line}",')
    
    return f'''// Code generated by scale_logo.py - DO NOT EDIT
package theme

import (
	"strings"

	"github.com/charmbracelet/lipgloss"
)

var {logo_name}LogoLines = []string{{
{chr(10).join(line_strs)}
}}

var {logo_name}GradientColors = []lipgloss.Color{{{chr(10).join(palette_lines)}
}}

func Render{logo_name.title()}Logo() string {{
	total := len({logo_name}LogoLines)
	if total == 0 {{
		return ""
	}}

	bands := len({logo_name}GradientColors)
	var b strings.Builder

	for i, line := range {logo_name}LogoLines {{
		bandIdx := (i * bands) / total
		if bandIdx >= bands {{
			bandIdx = bands - 1
		}}
		style := lipgloss.NewStyle().Foreground({logo_name}GradientColors[bandIdx])
		b.WriteString(style.Render(line))
		if i < total-1 {{
			b.WriteByte('\\n')
		}}
	}}

	return b.String()
}}
'''

if __name__ == "__main__":
    lines, palette = create_scaled_logo(80, 16)
    code = generate_go_code(lines, palette, "futuristic")
    print(code)
